#!/usr/bin/env node
// Build the pilot equipment database from Massif Press's open lancer-data
// and the tracker's Russian translation catalog.
const fs = require('node:fs');
const path = require('node:path');

const here = __dirname;
const readJson = name => JSON.parse(fs.readFileSync(path.join(here, name), 'utf8').replace(/^\uFEFF/, ''));
const source = readJson('pilot_gear.json');
const translations = readJson('ru_pilot_gear.json');
const seen = new Set();

for (const item of source) {
  if (!item.id || seen.has(item.id)) throw new Error(`Missing or duplicate pilot gear id: ${item.id}`);
  seen.add(item.id);
  const ru = translations[item.id];
  if (!ru || !ru.name) throw new Error(`Missing Russian name: ${item.id}`);
  for (const field of ['effect', 'description']) {
    if (item[field] && !ru[field]) throw new Error(`Missing Russian ${field}: ${item.id}`);
  }
  if ((item.actions || []).length !== (ru.actions || []).length) {
    throw new Error(`Russian action count does not match: ${item.id}`);
  }
  item.ru = ru;
}

for (const id of Object.keys(translations)) {
  if (!seen.has(id)) throw new Error(`Translation has no source item: ${id}`);
}

const output = '// Generated by build_pilot_gear.js from pilot_gear.json and ru_pilot_gear.json.\n'
  + '// Source: https://github.com/massif-press/lancer-data/blob/master/lib/pilot_gear.json\n'
  + 'const PILOT_GEAR_DB = ' + JSON.stringify(source, null, 2) + ';\n';
fs.writeFileSync(path.join(here, 'pilot_gear_db.js'), output, 'utf8');
console.log(`Pilot equipment: ${source.length} items, ${Buffer.byteLength(output)} bytes`);
